// Config is the on-disk server configuration (/etc/gft/server.json, mode 0600).
type Config struct {
	Listen           string      `json:"listen"`
	PublicHost       string      `json:"public_host"`
	SNI              string      `json:"sni"`
	PSK              string      `json:"psk"`                 // base64
	CertMode         string      `json:"cert_mode,omitempty"` // "acme", "file", "self_signed_90d"
	CertFile         string      `json:"cert_file,omitempty"`
	KeyFile          string      `json:"key_file,omitempty"`
	ACMEDomains      []string    `json:"acme_domains,omitempty"`
	ACMECacheDir     string      `json:"acme_cache_dir,omitempty"`
	ACMEEmail        string      `json:"acme_email,omitempty"`
	FallbackMode     string      `json:"fallback_mode,omitempty"`     // "mirror" (default), "reverse_proxy", "builtin_blog"
	FallbackTarget   string      `json:"fallback_target,omitempty"`   // e.g. "http://127.0.0.1:8080"
	CamouflageTarget string      `json:"camouflage_target,omitempty"` // e.g. "<selected-sni>:443"
	HopRange         string      `json:"hop_range,omitempty"`         // e.g. "20000-40000"
	Remark           string      `json:"remark,omitempty"`            // custom exported link remark (e.g. "Tokyo-Main")
	DisableRTC       bool        `json:"disable_rtc,omitempty"`
	DisableQUIC      bool        `json:"disable_quic,omitempty"`  // legacy alias for DisableRTC
	TxMbps           int         `json:"tx_mbps,omitempty"`       // optional server Smart-Brutal max TX Mbps (0 = Auto)
	UpMbps           int         `json:"up_mbps,omitempty"`       // default exported client Smart-Brutal uplink Mbps (0 = Auto)
	DownMbps         int         `json:"down_mbps,omitempty"`     // default exported client Smart-Brutal downlink Mbps (0 = Auto)
	MaxMemoryMB      int         `json:"max_memory_mb,omitempty"` // process memory soft cap in MiB (default 512)
	Params           *gft.Params `json:"params,omitempty"`
	PanelPath        string      `json:"panel_path"` // e.g. /ksl-panel-xxxxxxxx
	PanelHash        string      `json:"panel_hash"` // bcrypt
	Pin              string      `json:"pin"`        // SPKI SHA-256 hex
	StateDir         string      `json:"state_dir"`
}

// EffectiveMaxMemoryMB returns the configured MiB ceiling or default 512 MiB.
func (c *Config) EffectiveMaxMemoryMB() int {
	if c != nil && c.MaxMemoryMB > 0 {
		return c.MaxMemoryMB
	}
	return 512
}

// IsRTCDisabled reports whether Kestrel-RTC UDP transport is disabled in server config.
func (c *Config) IsRTCDisabled() bool {
	return c != nil && (c.DisableRTC || c.DisableQUIC)
}

func LoadConfig(path string) (*Config, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var c Config
	if err := json.Unmarshal(b, &c); err != nil {
		return nil, err
	}
	if c.Listen == "" || c.PSK == "" || c.PanelPath == "" || c.PanelHash == "" {
		return nil, errors.New("incomplete config")
	}
	if c.CertMode == "" {
		c.CertMode = "file"
	}
	if c.FallbackMode == "" {
		if c.FallbackTarget != "" {
			c.FallbackMode = "reverse_proxy"
		} else {
			c.FallbackMode = "mirror"
		}
	}
	if c.CamouflageTarget == "" && c.FallbackMode == "mirror" && c.SNI != "" {
		c.CamouflageTarget = net.JoinHostPort(c.SNI, "443")
	}
	return &c, nil
}

// Secrets are generated by Init and printed once.
type Secrets struct {
	Host          string `json:"host"`
	Port          int    `json:"port"`
	SNI           string `json:"sni"`
	PSK           string `json:"psk"`
	Pin           string `json:"pin"`
	Verify        string `json:"verify"`
	PanelPath     string `json:"panel_path"`
	PanelPassword string `json:"panel_password"`
	Link          string `json:"link"`
	Created       bool   `json:"created"`
}

func randString(n int, alphabet string) string {
	out := make([]byte, n)
	max := big.NewInt(int64(len(alphabet)))
	for i := range out {
		v, _ := rand.Int(rand.Reader, max)
		out[i] = alphabet[v.Int64()]
	}
	return string(out)
}

// InitOptions configures server initialization.
type InitOptions struct {
	ConfDir          string
	StateDir         string
	Host             string
	SNI              string
	Listen           string
	CertMode         string
	CertFile         string
	KeyFile          string
	ACMEDomains      []string
	ACMECacheDir     string
	ACMEEmail        string
	FallbackMode     string
	FallbackTarget   string
	CamouflageTarget string
	HopRange         string
}

// Init idempotently initializes server config, certificates, PSK, and stealth panel credentials.
func Init(confDir, stateDir, host, sni, listen string) (*Secrets, error) {
	return InitWithOptions(InitOptions{
		ConfDir:  confDir,
		StateDir: stateDir,
		Host:     host,
		SNI:      sni,
		Listen:   listen,
		CertMode: "self_signed_90d",
	})
}

// InitWithOptions idempotently creates server configuration with explicit cert and fallback modes.
func InitWithOptions(opts InitOptions) (*Secrets, error) {
	if opts.Listen == "" {
		opts.Listen = ":443"
	}
	if opts.SNI == "" || opts.SNI == "auto" {
		opts.SNI = pickDefaultSNI(opts.Host)
	}
	if opts.CertMode == "" {
		opts.CertMode = "self_signed_90d"
	}
	if opts.FallbackMode == "" {
		if opts.FallbackTarget != "" {
			opts.FallbackMode = "reverse_proxy"
		} else {
			opts.FallbackMode = "mirror"
		}
	}
	if opts.CamouflageTarget == "" && opts.FallbackMode == "mirror" && opts.SNI != "" {
		opts.CamouflageTarget = net.JoinHostPort(opts.SNI, "443")
	}

	cfgPath := filepath.Join(opts.ConfDir, "server.json")
	if c, err := LoadConfig(cfgPath); err == nil {
		return secretsFrom(c, "", false), nil
	}
	if err := os.MkdirAll(opts.ConfDir, 0o750); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(opts.StateDir, 0o750); err != nil {
		return nil, err
	}

	certFile := opts.CertFile
	keyFile := opts.KeyFile
	var pinHex string

	switch opts.CertMode {
	case "self_signed_90d":
		key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			return nil, err
		}
		der, pin, err := generateLeafCert(key, &key.PublicKey, opts.SNI)
		if err != nil {
			return nil, err
		}
		pinHex = pin

		kb, _ := x509.MarshalECPrivateKey(key)
		certFile, keyFile = filepath.Join(opts.ConfDir, "cert.pem"), filepath.Join(opts.ConfDir, "key.pem")
		if err := WriteFileAtomic(certFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
			return nil, err
		}
		if err := WriteFileAtomic(keyFile, pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: kb}), 0o600); err != nil {
			return nil, err
		}
	case "file":
		if certFile == "" || keyFile == "" {
			return nil, errors.New("cert_mode=file requires cert_file and key_file")
		}
		if b, err := os.ReadFile(certFile); err == nil {
			if blk, _ := pem.Decode(b); blk != nil {
				if leaf, err := x509.ParseCertificate(blk.Bytes); err == nil {
					pinHex = gft.SPKIOf(leaf)
				}
			}
		}
	case "acme":
		if opts.ACMECacheDir == "" {
			opts.ACMECacheDir = filepath.Join(opts.StateDir, "acme")
		}
		_ = os.MkdirAll(opts.ACMECacheDir, 0o700)
	default:
		return nil, errors.New("unsupported cert_mode: " + opts.CertMode)
	}

	psk := make([]byte, 32)
	_, _ = rand.Read(psk)
	pass := randString(20, "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789")
	hash, err := bcrypt.GenerateFromPassword([]byte(pass), 12)
	if err != nil {
		return nil, err
	}

	c := &Config{
		Listen:           opts.Listen,
		PublicHost:       opts.Host,
		SNI:              opts.SNI,
		PSK:              base64.StdEncoding.EncodeToString(psk),
		CertMode:         opts.CertMode,
		CertFile:         certFile,
		KeyFile:          keyFile,
		ACMEDomains:      opts.ACMEDomains,
		ACMECacheDir:     opts.ACMECacheDir,
		ACMEEmail:        opts.ACMEEmail,
		FallbackMode:     opts.FallbackMode,
		FallbackTarget:   opts.FallbackTarget,
		CamouflageTarget: opts.CamouflageTarget,
		HopRange:         opts.HopRange,
		PanelPath:        "/ksl-panel-" + randString(32, "abcdefghijklmnopqrstuvwxyz0123456789"),
		PanelHash:        string(hash),
		Pin:              pinHex,
		StateDir:         opts.StateDir,
	}
	b, _ := json.MarshalIndent(c, "", "  ")
	if err := WriteFileAtomic(cfgPath, b, 0o600); err != nil {
		return nil, err
	}
	return secretsFrom(c, pass, true), nil
}

func pickDefaultSNI(selfHost string) string {
	pool := sni.FlattenPool(sni.LoadPool(""))
	if !testing.Testing() {
		ctx, cancel := context.WithTimeout(context.Background(), 4*time.Second)
		pick, _, err := sni.AutoSelectSNI(ctx, selfHost)
		cancel()
		if err == nil && pick.Domain != "" {
			return pick.Domain
		}
	}
	if len(pool) > 0 {
		idx, err := rand.Int(rand.Reader, big.NewInt(int64(len(pool))))
		if err == nil {
			return pool[int(idx.Int64())].Domain
		}
		return pool[0].Domain
	}
	return "ftp.jaist.ac.jp"
}

func generateLeafCert(signer crypto.Signer, pub crypto.PublicKey, sniName string) ([]byte, string, error) {
	serial, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 120))
	backDaysBig, _ := rand.Int(rand.Reader, big.NewInt(7))
	backDays := int(backDaysBig.Int64()) + 1
	notBefore := time.Now().AddDate(0, 0, -backDays)
	tmpl := &x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: sniName},
		DNSNames:     []string{sniName}, // Strictly no public IP in SAN
		NotBefore:    notBefore,
		NotAfter:     notBefore.AddDate(0, 0, 90),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, pub, signer)
	if err != nil {
		return nil, "", err
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, "", err
	}
	sum := sha256.Sum256(leaf.RawSubjectPublicKeyInfo)
	return der, hex.EncodeToString(sum[:]), nil
}

func parsePrivateKeyPEM(pemBytes []byte) (crypto.Signer, crypto.PublicKey, error) {
	blk, _ := pem.Decode(pemBytes)
	if blk == nil {
		return nil, nil, errors.New("invalid PEM key")
	}
	if k, err := x509.ParseECPrivateKey(blk.Bytes); err == nil {
		return k, &k.PublicKey, nil
	}
	if k, err := x509.ParsePKCS8PrivateKey(blk.Bytes); err == nil {
		switch s := k.(type) {
		case *ecdsa.PrivateKey:
			return s, &s.PublicKey, nil
		case *rsa.PrivateKey:
			return s, &s.PublicKey, nil
		}
	}
	if k, err := x509.ParsePKCS1PrivateKey(blk.Bytes); err == nil {
		return k, &k.PublicKey, nil
	}
	return nil, nil, errors.New("unsupported private key format")
}

// WriteFileAtomic writes data via temporary file + fsync + atomic rename.
func WriteFileAtomic(path string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	tmp := path + ".tmp"
	f, err := os.OpenFile(tmp, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, perm)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = os.Remove(tmp)
		return err
	}
	_ = f.Sync()
	if err := f.Close(); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	preserveFileOwnership(tmp, path, perm)
	return os.Rename(tmp, path)
}

// SaveConfigAtomic serializes Config cleanly via WriteFileAtomic.
func SaveConfigAtomic(cfgPath string, c *Config) error {
	b, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return err
	}
	b = append(b, '\n')
	return WriteFileAtomic(cfgPath, b, 0o600)
}

// RotateSNI replaces the camouflage SNI while preserving the existing private key
// so leaf certificate SPKI Pin stays 100% invariant for existing clients.
func RotateSNI(cfgPath, newSNI string) (string, error) {
	if newSNI == "" {
		return "", errors.New("newSNI required")
	}
	c, err := LoadConfig(cfgPath)
	if err != nil {
		return "", err
	}
	if c.KeyFile != "" && c.CertFile != "" && (c.CertMode == "self_signed_90d" || c.CertMode == "file") {
		kb, err := os.ReadFile(c.KeyFile)
		if err != nil {
			return "", err
		}
		signer, pub, err := parsePrivateKeyPEM(kb)
		if err != nil {
			return "", err
		}
		der, pinHex, err := generateLeafCert(signer, pub, newSNI)
		if err != nil {
			return "", err
		}
		if err := WriteFileAtomic(c.CertFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
			return "", err
		}
		c.Pin = pinHex
	}
	c.SNI = newSNI
	if c.FallbackMode == "mirror" || c.FallbackMode == "" {
		c.FallbackMode = "mirror"
		c.CamouflageTarget = net.JoinHostPort(newSNI, "443")
	}
	if err := SaveConfigAtomic(cfgPath, c); err != nil {
		return "", err
	}
	return c.Pin, nil
}

// RotatePSK generates a fresh 32-byte base64 pre-shared key.
func RotatePSK() (string, error) {
	psk := make([]byte, 32)
	if _, err := rand.Read(psk); err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString(psk), nil
}

// RotatePanelCreds generates a fresh secret panel path and 20-char admin password + bcrypt hash.
func RotatePanelCreds() (panelPath, password, bcryptHash string, err error) {
	path := "/ksl-panel-" + randString(32, "abcdefghijklmnopqrstuvwxyz0123456789")
	pass := randString(20, "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789")
	hash, herr := bcrypt.GenerateFromPassword([]byte(pass), 12)
	if herr != nil {
		return "", "", "", herr
	}
	return path, pass, string(hash), nil
}

// RegenerateKeypair creates a brand new ECDSA P-256 keypair and 90-day leaf cert for c.SNI,
// writing cert.pem/key.pem atomically and updating c.Pin.
func RegenerateKeypair(c *Config) error {
	if c.CertFile == "" || c.KeyFile == "" {
		return errors.New("cert_file and key_file required")
	}
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	sniName := c.SNI
	if sniName == "" {
		sniName = "ftp.jaist.ac.jp"
	}
	der, pinHex, err := generateLeafCert(key, &key.PublicKey, sniName)
	if err != nil {
		return err
	}
	kb, _ := x509.MarshalECPrivateKey(key)
	if err := WriteFileAtomic(c.KeyFile, pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: kb}), 0o600); err != nil {
		return err
	}
	if err := WriteFileAtomic(c.CertFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
		return err
	}
	c.Pin = pinHex
	c.CertMode = "self_signed_90d"
	return nil
}

func listenPort(listen string) int {
	_, ps, err := net.SplitHostPort(listen)
	if err != nil {
		return 443
	}
	p, _ := strconv.Atoi(ps)
	if p <= 0 {
		return 443
	}
	return p
}

func (c *Config) Link(p gft.Params) *gft.Link {
	port := listenPort(c.Listen)
	verify := "spki"
	if c.CertMode == "acme" || (c.CertMode == "file" && c.Pin == "") {
		verify = "ca"
	}
	remark := strings.TrimSpace(c.Remark)
	if remark == "" {
		remark = "Kestrel-RTC-v4.0"
	}
	return &gft.Link{
		V:         4,
		Host:      c.PublicHost,
		Port:      port,
		SNI:       c.SNI,
		PSK:       c.PSK,
		Verify:    verify,
		Pin:       c.Pin,
		FP:        "chrome",
		Transport: "auto",
		SplitSNI:  true,
		HopRange:  c.HopRange,
		UpMbps:    c.UpMbps,
		DownMbps:  c.DownMbps,
		Params:    &p,
		Remark:    remark,
	}
}

func secretsFrom(c *Config, pass string, created bool) *Secrets {
	p := gft.DefaultParams()
	if c.Params != nil && c.Params.Validate() == nil {
		p = *c.Params
	}
	l := c.Link(p)
	return &Secrets{
		Host:          c.PublicHost,
		Port:          listenPort(c.Listen),
		SNI:           c.SNI,
		PSK:           c.PSK,
		Pin:           c.Pin,
		Verify:        l.EffectiveVerify(),
		PanelPath:     c.PanelPath,
		PanelPassword: pass,
		Link:          l.Encode(),
		Created:       created,
	}
}
